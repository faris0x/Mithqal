#!/usr/bin/env python3
"""Generate differential fixtures with SymPy.

The generated files are committed so the Rust test suite does not require
SymPy. Regenerate with:

    python3 tools/generate_differential_fixtures.py

This script is developer tooling and is not part of the crate build.
"""

from pathlib import Path
import re

import sympy as sp

ROOT = Path(__file__).resolve().parents[1]

x, y, z = sp.symbols("x y z")
a, b, c, d = sp.symbols("a b c d")


def to_mit(expression):
    text = sp.sstr(expression)
    text = re.sub(r"\bAbs\(", "abs(", text)
    text = re.sub(r"\blog\(", "ln(", text)
    text = re.sub(r"\bE\b", "e", text)
    text = re.sub(r"\bI\b", "i", text)
    text = re.sub(r"\boo\b", "inf", text)
    text = text.replace("**", "^")
    return "".join(text.split())


def matrix_to_mit(matrix):
    rows = []
    for row in matrix.tolist():
        rows.append("[" + ",".join(to_mit(value) for value in row) + "]")
    return "[" + ",".join(rows) + "]"


def write(name, records):
    lines = [
        "# Generated by tools/generate_differential_fixtures.py with SymPy "
        + sp.__version__,
        "# Fields are tab separated. Comments and blank lines are ignored.",
    ]
    for record in records:
        lines.append("\t".join(record))
    (ROOT / "tests/fixtures/differential" / name).write_text("\n".join(lines) + "\n")


algebra = []
polynomials = [
    x**2 - 1,
    x**3 - 1,
    x**4 - 5 * x**2 + 4,
    6 * x**2 + 5 * x + 1,
    2 * x**2 + 5 * x + 2,
    x**2 + 2 * x * y + y**2,
    x**2 - y**2,
    x**3 - 6 * x**2 + 11 * x - 6,
    (x + y) * (x - y + 1),
    4 * x**2 + 4 * x + 1,
    x**2 + 2 * x + 1,
    x**3 + 3 * x**2 + 3 * x + 1,
    2 * x**3 - 2 * x,
    x**4 + 2 * x**2 + 1,
    x**2 * y**2 - 1,
]
for polynomial in polynomials:
    algebra.append(("factor", to_mit(polynomial), to_mit(sp.factor(polynomial))))

for expression in [
    (x + 1) ** 5,
    (x + y + z) ** 3,
    (x + 2 * y) * (x - y + 1),
    (x + y) * (x - y) * (x**2 + y**2),
    (2 * x + 3) ** 4,
    (x + 1) * (x + 2) * (x + 3),
    (x + y) ** 4,
]:
    algebra.append(("expand", to_mit(expression), to_mit(sp.expand(expression))))

write("algebra.tsv", algebra)

calculus = []
for expression in [
    x**5 - 3 * x**3 + 2 * x,
    sp.sin(x) * sp.cos(x),
    sp.exp(2 * x),
    sp.log(x),
    1 / (x + 1),
    x * sp.exp(x),
    sp.atan(x),
    x**2 * sp.sin(x),
]:
    calculus.append(("diff", "x", to_mit(expression), to_mit(sp.expand(sp.diff(expression, x)))))

for expression in [
    x**4 - 2 * x**2 + 1,
    sp.sin(2 * x),
    sp.exp(3 * x),
    x * sp.exp(x),
    sp.log(x),
    sp.atan(x),
    sp.cos(2 * x),
    x**2 * sp.exp(x),
]:
    calculus.append(
        ("integrate", "x", to_mit(expression), to_mit(sp.expand(sp.integrate(expression, x))))
    )

for expression, point in [
    ((x**2 - 1) / (x - 1), 1),
    ((x**3 - 1) / (x - 1), 1),
    ((x**2 - 4) / (x - 2), 2),
    ((2 * x + 1) / (x + 3), sp.oo),
    ((x + 1) / (x**2 + 1), sp.oo),
    (x**2, 2),
    ((x**2 + 3 * x + 2) / (x + 1), -1),
    ((3 * x**2 + 2) / (x**2 - 1), sp.oo),
]:
    calculus.append(
        ("limit", "x", to_mit(point), to_mit(expression), to_mit(sp.limit(expression, x, point)))
    )

write("calculus.tsv", calculus)

linalg = []
for matrix in [
    sp.Matrix([[1, 2], [3, 4]]),
    sp.Matrix([[2, 0], [0, 3]]),
    sp.Matrix([[1, 2, 3], [4, 5, 6], [7, 8, 10]]),
    sp.Matrix([[a, b], [c, d]]),
]:
    linalg.append(("det", matrix_to_mit(matrix), to_mit(matrix.det())))

for matrix in [
    sp.Matrix([[1, 2], [3, 4]]),
    sp.Matrix([[2, 0], [0, 4]]),
    sp.Matrix([[1, 1], [1, 2]]),
    sp.Matrix([[3, 1], [2, 1]]),
]:
    linalg.append(("inverse", matrix_to_mit(matrix), matrix_to_mit(matrix.inv())))

write("linalg.tsv", linalg)

def probe_record(expression, assignments, expected):
    substitutions = {symbol: value for symbol, value in assignments}
    value = sp.N(expected.subs(substitutions), 50)
    assignment_text = ",".join(
        f"{symbol.name}={to_mit(value)}" for symbol, value in assignments
    )
    return ("probe", assignment_text, expression, str(value))


probes = []
for expression, points in [
    (x**5 - 3 * x**3 + 2 * x, [sp.Rational(-3, 2), sp.Rational(1, 3), sp.Rational(5, 2)]),
    (sp.sin(x) * sp.cos(x), [sp.Rational(-1, 2), sp.Rational(1, 3), sp.Rational(2, 1)]),
    (sp.exp(2 * x), [sp.Rational(-1, 1), sp.Rational(0, 1), sp.Rational(1, 1)]),
    (sp.log(x), [sp.Rational(1, 2), sp.Rational(2, 1), sp.Rational(3, 1)]),
    (1 / (x + 1), [sp.Rational(-2, 1), sp.Rational(1, 2), sp.Rational(3, 1)]),
    (x * sp.exp(x), [sp.Rational(-1, 1), sp.Rational(1, 2), sp.Rational(2, 1)]),
    (sp.atan(x), [sp.Rational(-1, 1), sp.Rational(0, 1), sp.Rational(1, 1)]),
    (x**2 * sp.sin(x), [sp.Rational(-1, 1), sp.Rational(1, 2), sp.Rational(2, 1)]),
]:
    for point in points:
        probes.append(
            probe_record(
                f"differentiate({to_mit(expression)},x)",
                [(x, point)],
                sp.diff(expression, x),
            )
        )

for expression, points in [
    (x**4 - 2 * x**2 + 1, [sp.Rational(-1, 1), sp.Rational(1, 2), sp.Rational(2, 1)]),
    (sp.sin(2 * x), [sp.Rational(-1, 1), sp.Rational(0, 1), sp.Rational(1, 1)]),
    (sp.exp(3 * x), [sp.Rational(-1, 1), sp.Rational(0, 1), sp.Rational(1, 1)]),
    (x * sp.exp(x), [sp.Rational(-1, 1), sp.Rational(1, 2), sp.Rational(2, 1)]),
    (sp.log(x), [sp.Rational(1, 2), sp.Rational(2, 1), sp.Rational(3, 1)]),
    (sp.atan(x), [sp.Rational(-1, 1), sp.Rational(0, 1), sp.Rational(1, 1)]),
    (sp.cos(2 * x), [sp.Rational(-1, 1), sp.Rational(0, 1), sp.Rational(1, 1)]),
    (x**2 * sp.exp(x), [sp.Rational(-1, 1), sp.Rational(1, 2), sp.Rational(2, 1)]),
]:
    for point in points:
        probes.append(
            probe_record(
                f"integrate({to_mit(expression)},x)",
                [(x, point)],
                sp.integrate(expression, x),
            )
        )

for expression, point in [
    ((x**2 - 1) / (x - 1), 1),
    ((x**3 - 1) / (x - 1), 1),
    ((x**2 - 4) / (x - 2), 2),
    ((2 * x + 1) / (x + 3), sp.oo),
    ((x + 1) / (x**2 + 1), sp.oo),
    (x**2, 2),
    ((x**2 + 3 * x + 2) / (x + 1), -1),
    ((3 * x**2 + 2) / (x**2 - 1), sp.oo),
]:
    limit_expression = f"limit({to_mit(expression)},x,{to_mit(point)})"
    probes.append(probe_record(limit_expression, [], sp.limit(expression, x, point)))

for matrix in [
    sp.Matrix([[1, 2], [3, 4]]),
    sp.Matrix([[2, 0], [0, 3]]),
    sp.Matrix([[1, 2, 3], [4, 5, 6], [7, 8, 10]]),
    sp.Matrix([[a, b], [c, d]]),
]:
    assignments = []
    for symbol in sorted(matrix.free_symbols, key=lambda value: value.name):
        assignments.append((symbol, {a: sp.Rational(1, 2), b: -2, c: 3, d: 5}[symbol]))
    probes.append(
        probe_record(
            f"det({matrix_to_mit(matrix)})",
            assignments,
            matrix.det(),
        )
    )

write("probes.tsv", probes)

