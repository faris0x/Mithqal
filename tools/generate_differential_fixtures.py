def to_mit(expression):
    text = sp.sstr(expression)
    text = re.sub(r"\bAbs\(", "abs(", text)
    text = re.sub(r"\blog\(", "ln(", text)
    text = re.sub(r"\bE\b", "e", text)
    text = re.sub(r"\bI\b", "i", text)
    text = re.sub(r"\boo\b", "inf", text)
    text = text.replace("**", "^")
    return "".join(text.split())


def matrix_to_mit(matrix):
    rows = []
    for row in matrix.tolist():
        rows.append("[" + ",".join(to_mit(value) for value in row) + "]")
    return "[" + ",".join(rows) + "]"


def write(name, records):
    lines = [
        "# Generated by tools/generate_differential_fixtures.py with SymPy "
        + sp.__version__,
        "# Fields are tab separated. Comments and blank lines are ignored.",
    ]
    for record in records:
        lines.append("\t".join(record))
    (ROOT / "tests/fixtures/differential" / name).write_text("\n".join(lines) + "\n")


