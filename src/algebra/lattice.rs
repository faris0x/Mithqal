//! Exact lattice algorithms: Hermite and Smith normal forms, LLL reduction,
//! and bounded enumeration of short vectors.
//!
//! These are the computational base for ideals, class groups, and unit groups.
//! Everything is exact. No floating point enters the reduction or the normal
//! forms. LLL uses rational Gram-Schmidt and is intended for the modest
//! dimensions of the number field layer.

#[allow(unused_imports)]
use crate::prelude::*;

use core::cmp::Ordering;

use crate::num::{Int, Rat};

use super::intmatrix::{IntMatrix, div_exact, div_rem_euclid, extended_gcd};
use super::ratmatrix::RatMatrix;

/// Row style Hermite normal form.
///
/// Each pivot column has one positive entry, every entry below it is zero, and
/// entries above it are reduced into `[0, pivot)`.
#[allow(clippy::needless_range_loop)]
pub(crate) fn hermite_normal_form(matrix: &IntMatrix) -> IntMatrix {
    let mut result = matrix.clone();
    let rows = result.row_count();
    let columns = result.column_count();
    let mut pivot_row = 0usize;
    for column in 0..columns {
        if pivot_row >= rows {
            break;
        }
        let Some(pivot) = (pivot_row..rows).find(|row| !result.get(*row, column).is_zero()) else {
            continue;
        };
        if pivot != pivot_row {
            result.swap_rows(pivot, pivot_row);
        }
        if result.get(pivot_row, column).sign() < 0 {
            result.scale_row(pivot_row, &Int::from_i64(-1));
        }
        loop {
            let pivot_value = result.get(pivot_row, column);
            let mut changed = false;
            for row in pivot_row + 1..rows {
                let entry = result.get(row, column);
                if entry.is_zero() {
                    continue;
                }
                if divides_exact(&pivot_value, &entry) {
                    let factor = div_exact(&entry, &pivot_value);
                    result.add_row_multiple(row, pivot_row, &factor.neg());
                    changed = true;
                } else {
                    let (gcd, s, t) = extended_gcd(&pivot_value, &entry);
                    let source_row = result.row(pivot_row);
                    let other_row = result.row(row);
                    let other_factor = div_exact(&entry, &gcd).neg();
                    let pivot_factor = div_exact(&pivot_value, &gcd);
                    let new_pivot = combine(&source_row, &other_row, &s, &t);
                    let new_other = combine(&source_row, &other_row, &other_factor, &pivot_factor);
                    result.set_row(pivot_row, new_pivot);
                    result.set_row(row, new_other);
                    changed = true;
                }
            }
            if !changed {
                break;
            }
        }
        let pivot_value = result.get(pivot_row, column);
        for row in 0..pivot_row {
            let entry = result.get(row, column);
            if entry.is_zero() {
                continue;
            }
            let (quotient, _) = div_rem_euclid(&entry, &pivot_value);
            if !quotient.is_zero() {
                result.add_row_multiple(row, pivot_row, &quotient.neg());
            }
        }
        pivot_row += 1;
    }
    result.without_zero_rows()
}

/// A reduced basis of the column lattice generated by a matrix.
///
/// Uses the transpose Smith form to obtain a basis without the coefficient
/// growth that plain Hermite elimination can suffer on redundant generators,
/// then LLL-reduces the basis.
pub(crate) fn generator_lattice_basis(matrix: &IntMatrix) -> Option<IntMatrix> {
    let rows = matrix.row_count();
    let columns = matrix.column_count();
    if rows == 0 || columns == 0 {
        return None;
    }
    let (diagonal, transform) = smith_normal_form_with_column_transform(&matrix.transpose())?;
    let transform = RatMatrix::from_rows(
        transform
            .to_rows()
            .iter()
            .map(|row| row.iter().map(int_to_rat).collect())
            .collect(),
    )?;
    let inverse = transform.inverse()?;
    let mut basis = Vec::with_capacity(rows);
    for index in 0..rows {
        let value = diagonal.get(index, index);
        if value.is_zero() {
            return None;
        }
        let row = inverse.row(index);
        if !row.iter().all(|entry| entry.den().is_one()) {
            return None;
        }
        basis.push(
            row.iter()
                .map(|entry| entry.num().mul(&value))
                .collect::<Vec<_>>(),
        );
    }
    let reduced = lll_reduce(&basis, &default_delta())?;
    IntMatrix::from_columns(reduced)
}

/// Column style Hermite normal form, used when a lattice is described by
/// columns.
pub(crate) fn column_hermite_normal_form(matrix: &IntMatrix) -> IntMatrix {
    hermite_normal_form(&matrix.transpose()).transpose()
}

/// The index of a full rank lattice generated by the rows, or `None` when the
/// matrix is not square or has zero determinant.
pub(crate) fn lattice_index(generators: &IntMatrix) -> Option<Int> {
    let determinant = generators.determinant()?;
    if determinant.is_zero() {
        None
    } else {
        Some(determinant.abs())
    }
}

/// The Smith normal form together with the unimodular transforms.
///
/// Returns `(d, u, v)` with `u * matrix * v = d`, `d` diagonal, non negative,
/// and each diagonal entry dividing the next.
#[allow(clippy::needless_range_loop)]
pub(crate) fn smith_normal_form(matrix: &IntMatrix) -> Option<(IntMatrix, IntMatrix, IntMatrix)> {
    let rows = matrix.row_count();
    let columns = matrix.column_count();
    let mut a = matrix.clone();
    let mut u = IntMatrix::identity(rows);
    let mut v = IntMatrix::identity(columns);
    let guard_limit = rows
        .saturating_mul(columns)
        .saturating_mul(32)
        .saturating_add(256);
    let mut guard = 0usize;
    let mut pivot = 0usize;
    while pivot < rows && pivot < columns {
        let Some((found_row, found_column)) = find_nonzero(&a, pivot) else {
            break;
        };
        if found_row != pivot {
            a.swap_rows(found_row, pivot);
            u.swap_rows(found_row, pivot);
        }
        if found_column != pivot {
            a.swap_columns(found_column, pivot);
            v.swap_columns(found_column, pivot);
        }
        loop {
            guard += 1;
            if guard > guard_limit {
                return None;
            }
            let mut changed = false;
            // Clear the pivot column.
            for row in 0..rows {
                if row == pivot {
                    continue;
                }
                let entry = a.get(row, pivot);
                if entry.is_zero() {
                    continue;
                }
                let pivot_value = a.get(pivot, pivot);
                if divides_exact(&pivot_value, &entry) {
                    let factor = div_exact(&entry, &pivot_value);
                    a.add_row_multiple(row, pivot, &factor.neg());
                    u.add_row_multiple(row, pivot, &factor.neg());
                    changed = true;
                } else {
                    let (gcd, s, t) = extended_gcd(&pivot_value, &entry);
                    let source_row = a.row(pivot);
                    let other_row = a.row(row);
                    let source_u = u.row(pivot);
                    let other_u = u.row(row);
                    let new_pivot_row = combine(&source_row, &other_row, &s, &t);
                    let other_factor = div_exact(&entry, &gcd).neg();
                    let pivot_factor = div_exact(&pivot_value, &gcd);
                    let new_other_row =
                        combine(&source_row, &other_row, &other_factor, &pivot_factor);
                    let new_pivot_u = combine(&source_u, &other_u, &s, &t);
                    let new_other_u = combine(&source_u, &other_u, &other_factor, &pivot_factor);
                    a.set_row(pivot, new_pivot_row);
                    a.set_row(row, new_other_row);
                    u.set_row(pivot, new_pivot_u);
                    u.set_row(row, new_other_u);
                    changed = true;
                }
            }
            // Clear the pivot row.
            for column in 0..columns {
                if column == pivot {
                    continue;
                }
                let entry = a.get(pivot, column);
                if entry.is_zero() {
                    continue;
                }
                let pivot_value = a.get(pivot, pivot);
                if divides_exact(&pivot_value, &entry) {
                    let factor = div_exact(&entry, &pivot_value);
                    a.add_column_multiple(column, pivot, &factor.neg());
                    v.add_column_multiple(column, pivot, &factor.neg());
                    changed = true;
                } else {
                    let (gcd, s, t) = extended_gcd(&pivot_value, &entry);
                    let source_column = a.column(pivot);
                    let other_column = a.column(column);
                    let source_v = v.column(pivot);
                    let other_v = v.column(column);
                    let new_pivot_column = combine(&source_column, &other_column, &s, &t);
                    let other_factor = div_exact(&entry, &gcd).neg();
                    let pivot_factor = div_exact(&pivot_value, &gcd);
                    let new_other_column =
                        combine(&source_column, &other_column, &other_factor, &pivot_factor);
                    let new_pivot_v = combine(&source_v, &other_v, &s, &t);
                    let new_other_v = combine(&source_v, &other_v, &other_factor, &pivot_factor);
                    a.set_column(pivot, new_pivot_column);
                    a.set_column(column, new_other_column);
                    v.set_column(pivot, new_pivot_v);
                    v.set_column(column, new_other_v);
                    changed = true;
                }
            }
            if !changed {
                break;
            }
        }
        // The pivot must divide every later entry. If not, add an offending
        // row into the pivot row and reduce again.
        let pivot_value = a.get(pivot, pivot);
        if pivot_value.is_zero() {
            pivot += 1;
            continue;
        }
        let mut offender = None;
        'scan: for row in pivot..rows {
            for column in pivot..columns {
                if row == pivot && column == pivot {
                    continue;
                }
                if !divides_exact(&pivot_value, &a.get(row, column)) {
                    offender = Some(row);
                    break 'scan;
                }
            }
        }
        if let Some(row) = offender {
            a.add_row_multiple(pivot, row, &Int::one());
            u.add_row_multiple(pivot, row, &Int::one());
            continue;
        }
        if a.get(pivot, pivot).sign() < 0 {
            a.scale_row(pivot, &Int::from_i64(-1));
            u.scale_row(pivot, &Int::from_i64(-1));
        }
        pivot += 1;
    }
    if u.determinant()?.abs() != Int::one() || v.determinant()?.abs() != Int::one() {
        return None;
    }
    let rebuilt = u.multiply(matrix)?.multiply(&v)?;
    if rebuilt != a {
        return None;
    }
    let size = rows.min(columns);
    for row in 0..rows {
        for column in 0..columns {
            if row != column && !a.get(row, column).is_zero() {
                return None;
            }
        }
    }
    let mut previous = Int::one();
    let mut saw_zero = false;
    for index in 0..size {
        let value = a.get(index, index);
        if value.sign() < 0 {
            return None;
        }
        if value.is_zero() {
            saw_zero = true;
            continue;
        }
        if saw_zero || !divides_exact(&previous, &value) {
            return None;
        }
        previous = value;
    }
    Some((a, u, v))
}

/// The Smith normal form with only the column transform.
///
/// Returns `(d, v)` where `d` is diagonal and `v` is unimodular. A left
/// transform exists but is not tracked or returned. This is intended for large
/// rectangular congruence matrices where constructing and verifying the left
/// transform is disproportionate.
#[allow(clippy::needless_range_loop)]
pub(crate) fn smith_normal_form_with_column_transform(
    matrix: &IntMatrix,
) -> Option<(IntMatrix, IntMatrix)> {
    let rows = matrix.row_count();
    let columns = matrix.column_count();
    let mut a = matrix.clone();
    let mut v = IntMatrix::identity(columns);
    let guard_limit = rows
        .saturating_mul(columns)
        .saturating_mul(32)
        .saturating_add(256);
    let mut guard = 0usize;
    let mut pivot = 0usize;
    while pivot < rows && pivot < columns {
        let Some((found_row, found_column)) = find_nonzero(&a, pivot) else {
            break;
        };
        if found_row != pivot {
            a.swap_rows(found_row, pivot);
        }
        if found_column != pivot {
            a.swap_columns(found_column, pivot);
            v.swap_columns(found_column, pivot);
        }
        loop {
            guard += 1;
            if guard > guard_limit {
                return None;
            }
            let mut changed = false;
            for row in 0..rows {
                if row == pivot {
                    continue;
                }
                let entry = a.get(row, pivot);
                if entry.is_zero() {
                    continue;
                }
                let pivot_value = a.get(pivot, pivot);
                if divides_exact(&pivot_value, &entry) {
                    let factor = div_exact(&entry, &pivot_value);
                    a.add_row_multiple(row, pivot, &factor.neg());
                    changed = true;
                } else {
                    let (gcd, s, t) = extended_gcd(&pivot_value, &entry);
                    let source_row = a.row(pivot);
                    let other_row = a.row(row);
                    let other_factor = div_exact(&entry, &gcd).neg();
                    let pivot_factor = div_exact(&pivot_value, &gcd);
                    let new_pivot_row = combine(&source_row, &other_row, &s, &t);
                    let new_other_row =
                        combine(&source_row, &other_row, &other_factor, &pivot_factor);
                    a.set_row(pivot, new_pivot_row);
                    a.set_row(row, new_other_row);
                    changed = true;
                }
            }
            for column in 0..columns {
                if column == pivot {
                    continue;
                }
                let entry = a.get(pivot, column);
                if entry.is_zero() {
                    continue;
                }
                let pivot_value = a.get(pivot, pivot);
                if divides_exact(&pivot_value, &entry) {
                    let factor = div_exact(&entry, &pivot_value);
                    a.add_column_multiple(column, pivot, &factor.neg());
                    v.add_column_multiple(column, pivot, &factor.neg());
                    changed = true;
                } else {
                    let (gcd, s, t) = extended_gcd(&pivot_value, &entry);
                    let source_column = a.column(pivot);
                    let other_column = a.column(column);
                    let source_v = v.column(pivot);
                    let other_v = v.column(column);
                    let new_pivot_column = combine(&source_column, &other_column, &s, &t);
                    let other_factor = div_exact(&entry, &gcd).neg();
                    let pivot_factor = div_exact(&pivot_value, &gcd);
                    let new_other_column =
                        combine(&source_column, &other_column, &other_factor, &pivot_factor);
                    let new_pivot_v = combine(&source_v, &other_v, &s, &t);
                    let new_other_v = combine(&source_v, &other_v, &other_factor, &pivot_factor);
                    a.set_column(pivot, new_pivot_column);
                    a.set_column(column, new_other_column);
                    v.set_column(pivot, new_pivot_v);
                    v.set_column(column, new_other_v);
                    changed = true;
                }
            }
            if !changed {
                break;
            }
        }
        let pivot_value = a.get(pivot, pivot);
        if pivot_value.is_zero() {
            pivot += 1;
            continue;
        }
        let mut offender = None;
        'scan: for row in pivot..rows {
            for column in pivot..columns {
                if row == pivot && column == pivot {
                    continue;
                }
                if !divides_exact(&pivot_value, &a.get(row, column)) {
                    offender = Some(row);
                    break 'scan;
                }
            }
        }
        if let Some(row) = offender {
            a.add_row_multiple(pivot, row, &Int::one());
            continue;
        }
        if a.get(pivot, pivot).sign() < 0 {
            a.scale_row(pivot, &Int::from_i64(-1));
        }
        pivot += 1;
    }
    if v.determinant()?.abs() != Int::one() {
        return None;
    }
    let size = rows.min(columns);
    for row in 0..rows {
        for column in 0..columns {
            if row != column && !a.get(row, column).is_zero() {
                return None;
            }
        }
    }
    let mut previous = Int::one();
    let mut saw_zero = false;
    for index in 0..size {
        let value = a.get(index, index);
        if value.sign() < 0 {
            return None;
        }
        if value.is_zero() {
            saw_zero = true;
            continue;
        }
        if saw_zero || !divides_exact(&previous, &value) {
            return None;
        }
        previous = value;
    }
    Some((a, v))
}

/// The nonzero diagonal entries of the Smith normal form, each at least one.
pub(crate) fn smith_invariants(matrix: &IntMatrix) -> Option<Vec<Int>> {
    let (diagonal, _, _) = smith_normal_form(matrix)?;
    let size = diagonal.row_count().min(diagonal.column_count());
    Some(
        (0..size)
            .map(|index| diagonal.get(index, index))
            .filter(|value| !value.is_zero())
            .collect(),
    )
}

/// The torsion invariants of the cokernel, that is the diagonal entries
/// greater than one.
pub(crate) fn cokernel_torsion(matrix: &IntMatrix) -> Option<Vec<Int>> {
    Some(
        smith_invariants(matrix)?
            .into_iter()
            .filter(|value| !value.is_one())
            .collect(),
    )
}

/// The free rank of the cokernel.
pub(crate) fn cokernel_free_rank(matrix: &IntMatrix) -> Option<usize> {
    let rank = smith_invariants(matrix)?.len();
    Some(matrix.row_count().saturating_sub(rank))
}

fn find_nonzero(matrix: &IntMatrix, start: usize) -> Option<(usize, usize)> {
    for row in start..matrix.row_count() {
        for column in start..matrix.column_count() {
            if !matrix.get(row, column).is_zero() {
                return Some((row, column));
            }
        }
    }
    None
}

fn divides_exact(divisor: &Int, value: &Int) -> bool {
    if divisor.is_zero() {
        return value.is_zero();
    }
    value
        .divrem(divisor)
        .map(|(_, remainder)| remainder.is_zero())
        .unwrap_or(false)
}

fn combine(left: &[Int], right: &[Int], left_factor: &Int, right_factor: &Int) -> Vec<Int> {
    left.iter()
        .zip(right)
        .map(|(a, b)| left_factor.mul(a).add(&right_factor.mul(b)))
        .collect()
}

/// The default LLL parameter.
pub(crate) fn default_delta() -> Rat {
    Rat::from_i64(3, 4).unwrap_or_else(|_| Rat::one())
}

/// LLL reduce an integer row basis.
///
/// Returns `None` when the rows are not linearly independent or the basis is
/// ragged.
pub(crate) fn lll_reduce(basis: &[Vec<Int>], delta: &Rat) -> Option<Vec<Vec<Int>>> {
    let count = basis.len();
    if count == 0 {
        return Some(Vec::new());
    }
    let width = basis[0].len();
    if basis.iter().any(|row| row.len() != width) {
        return None;
    }
    let mut vectors: Vec<Vec<Rat>> = basis
        .iter()
        .map(|row| row.iter().map(int_to_rat).collect())
        .collect();
    let mut mu = vec![vec![Rat::zero(); count]; count];
    let mut norms = vec![Rat::zero(); count];
    if !gram_schmidt(&vectors, &mut mu, &mut norms) {
        return None;
    }
    let mut index = 1usize;
    let mut guard = 0usize;
    let guard_limit = count.saturating_mul(count).saturating_mul(4096).max(4096);
    while index < count {
        guard += 1;
        if guard > guard_limit {
            return None;
        }
        for previous in (0..index).rev() {
            let nearest = mu[index][previous].round();
            if nearest.is_zero() {
                continue;
            }
            let factor = int_to_rat(&nearest);
            let previous_row = vectors[previous].clone();
            for (entry, previous_entry) in vectors[index].iter_mut().zip(&previous_row) {
                *entry = entry.sub(&factor.mul(previous_entry));
            }
            if !gram_schmidt(&vectors, &mut mu, &mut norms) {
                return None;
            }
        }
        let mu_previous = mu[index][index - 1].clone();
        let threshold = delta
            .sub(&mu_previous.mul(&mu_previous))
            .mul(&norms[index - 1]);
        if norms[index].cmp(&threshold) != Ordering::Less {
            index += 1;
        } else {
            vectors.swap(index, index - 1);
            if !gram_schmidt(&vectors, &mut mu, &mut norms) {
                return None;
            }
            index = index.saturating_sub(1).max(1);
        }
    }
    let mut reduced = Vec::with_capacity(count);
    for row in vectors {
        let mut integer_row = Vec::with_capacity(width);
        for value in row {
            if !value.den().is_one() {
                return None;
            }
            integer_row.push(value.num());
        }
        reduced.push(integer_row);
    }
    Some(reduced)
}

/// LLL reduce the rows of a matrix.
pub(crate) fn lll_reduce_matrix(matrix: &IntMatrix) -> Option<IntMatrix> {
    let reduced = lll_reduce(&matrix.to_rows(), &default_delta())?;
    IntMatrix::from_rows(reduced)
}

/// All nonzero lattice vectors with squared norm at most `bound`.
///
/// The input rows must be linearly independent and span the lattice. The
/// output vectors are actual lattice vectors, not coefficients in the reduced
/// basis. Dependent input yields no vectors.
pub(crate) fn short_lattice_vectors(basis: &IntMatrix, bound: &Int) -> Vec<Vec<Int>> {
    let original = basis.to_rows();
    if original.is_empty() {
        return Vec::new();
    }
    let width = original[0].len();
    let reduced = lll_reduce(&original, &default_delta()).unwrap_or_else(|| original.clone());
    let dimension = reduced.len();
    let mut gram = vec![vec![Rat::zero(); dimension]; dimension];
    for row in 0..dimension {
        for column in 0..dimension {
            let mut value = Rat::zero();
            for (left, right) in reduced[row].iter().zip(&reduced[column]) {
                value = value.add(&int_to_rat(left).mul(&int_to_rat(right)));
            }
            gram[row][column] = value;
        }
    }
    let mut mu = vec![vec![Rat::zero(); dimension]; dimension];
    let mut norms = vec![Rat::zero(); dimension];
    if !gram_schmidt_from_gram(&gram, &mut mu, &mut norms) {
        return Vec::new();
    }
    let mut enumeration = Enumeration {
        mu: &mu,
        norms: &norms,
        bound: int_to_rat(bound),
        bound_int: bound.clone(),
        coefficients: vec![Int::zero(); dimension],
        basis: &reduced,
        width,
        output: Vec::new(),
    };
    enumeration.run(dimension as isize - 1);
    enumeration.output
}

struct Enumeration<'a> {
    mu: &'a [Vec<Rat>],
    norms: &'a [Rat],
    bound: Rat,
    bound_int: Int,
    coefficients: Vec<Int>,
    basis: &'a [Vec<Int>],
    width: usize,
    output: Vec<Vec<Int>>,
}

impl Enumeration<'_> {
    #[allow(clippy::needless_range_loop)]
    fn run(&mut self, index: isize) {
        if index < 0 {
            if self.coefficients.iter().all(Int::is_zero) {
                return;
            }
            let mut vector = vec![Int::zero(); self.width];
            for (coefficient, basis) in self.coefficients.iter().zip(self.basis) {
                if coefficient.is_zero() {
                    continue;
                }
                for (entry, basis_entry) in vector.iter_mut().zip(basis) {
                    *entry = entry.add(&coefficient.mul(basis_entry));
                }
            }
            let mut norm = Int::zero();
            for entry in &vector {
                norm = norm.add(&entry.mul(entry));
            }
            if norm.cmp(&self.bound_int) == Ordering::Greater {
                return;
            }
            if !self.output.iter().any(|existing| existing == &vector) {
                self.output.push(vector);
            }
            return;
        }
        let position = index as usize;
        let dimension = self.mu.len();
        let mut offset = Rat::zero();
        for later in position + 1..dimension {
            offset =
                offset.add(&self.mu[later][position].mul(&int_to_rat(&self.coefficients[later])));
        }
        let center = offset.neg();
        let mut remaining = self.bound.clone();
        for later in position + 1..dimension {
            let mut value = int_to_rat(&self.coefficients[later]);
            for after in later + 1..dimension {
                value =
                    value.add(&self.mu[after][later].mul(&int_to_rat(&self.coefficients[after])));
            }
            remaining = remaining.sub(&self.norms[later].mul(&value.mul(&value)));
        }
        if remaining.sign() < 0 {
            return;
        }
        let ratio = match remaining.div(&self.norms[position]) {
            Ok(value) => value,
            Err(_) => return,
        };
        let radius = sqrt_rat_upper(&ratio);
        let low = center.sub(&radius).ceil();
        let high = center.add(&radius).floor();
        let mut value = low;
        while value.cmp(&high) != Ordering::Greater {
            self.coefficients[position] = value.clone();
            self.run(index - 1);
            value = value.add(&Int::one());
        }
    }
}

fn int_to_rat(value: &Int) -> Rat {
    Rat::from_ints(value.clone(), Int::one()).unwrap_or_else(|_| Rat::zero())
}

#[allow(clippy::needless_range_loop)]
fn gram_schmidt(vectors: &[Vec<Rat>], mu: &mut [Vec<Rat>], norms: &mut [Rat]) -> bool {
    let count = vectors.len();
    for row in 0..count {
        mu[row][row] = Rat::one();
        for column in 0..row {
            let mut value = Rat::zero();
            for entry in 0..vectors[row].len() {
                value = value.add(&vectors[row][entry].mul(&vectors[column][entry]));
            }
            for earlier in 0..column {
                value = value.sub(
                    &mu[row][earlier]
                        .mul(&mu[column][earlier])
                        .mul(&norms[earlier]),
                );
            }
            if norms[column].is_zero() {
                return false;
            }
            mu[row][column] = value.div(&norms[column]).unwrap_or_else(|_| Rat::zero());
        }
        let mut norm = Rat::zero();
        for entry in 0..vectors[row].len() {
            norm = norm.add(&vectors[row][entry].mul(&vectors[row][entry]));
        }
        for earlier in 0..row {
            norm = norm.sub(&mu[row][earlier].mul(&mu[row][earlier]).mul(&norms[earlier]));
        }
        if norm.sign() <= 0 {
            return false;
        }
        norms[row] = norm;
    }
    true
}

#[allow(clippy::needless_range_loop)]
fn gram_schmidt_from_gram(gram: &[Vec<Rat>], mu: &mut [Vec<Rat>], norms: &mut [Rat]) -> bool {
    let count = gram.len();
    for row in 0..count {
        mu[row][row] = Rat::one();
        for column in 0..row {
            let mut value = gram[row][column].clone();
            for earlier in 0..column {
                value = value.sub(
                    &mu[row][earlier]
                        .mul(&mu[column][earlier])
                        .mul(&norms[earlier]),
                );
            }
            if norms[column].is_zero() {
                return false;
            }
            mu[row][column] = value.div(&norms[column]).unwrap_or_else(|_| Rat::zero());
        }
        let mut norm = gram[row][row].clone();
        for earlier in 0..row {
            norm = norm.sub(&mu[row][earlier].mul(&mu[row][earlier]).mul(&norms[earlier]));
        }
        if norm.sign() <= 0 {
            return false;
        }
        norms[row] = norm;
    }
    true
}

/// A conservative rational upper bound for the square root.
fn sqrt_rat_upper(value: &Rat) -> Rat {
    if value.sign() <= 0 {
        return Rat::zero();
    }
    let product = value.num().abs().mul(&value.den());
    let root = integer_sqrt(&product);
    Rat::from_ints(root.add(&Int::one()), value.den()).unwrap_or_else(|_| Rat::zero())
}

/// Floor integer square root by Newton iteration.
pub(crate) fn integer_sqrt(value: &Int) -> Int {
    if value.sign() <= 0 {
        return Int::zero();
    }
    let two = Int::from_i64(2);
    let mut high = Int::one();
    while high.mul(&high).cmp(value) != Ordering::Greater {
        high = high.mul(&two);
    }
    let mut current = high;
    loop {
        let quotient = match value.divrem(&current) {
            Ok((quotient, _)) => quotient,
            Err(_) => return Int::zero(),
        };
        let next = match current.add(&quotient).divrem(&two) {
            Ok((quotient, _)) => quotient,
            Err(_) => return Int::zero(),
        };
        if next.cmp(&current) != Ordering::Less {
            return current;
        }
        current = next;
    }
}

