//! Orders in number fields and the p-radical Round 2 step.
//!
//! An order is stored by a rational basis in the power basis together with an
//! integer multiplication table. The p-maximal overorder is computed from the
//! p-radical and its multiplier ring. This is the Pohst-Zassenhaus strategy.

#[allow(unused_imports)]
use crate::prelude::*;

use core::cmp::Ordering;

use crate::num::{Int, Rat};

use super::super::dense::lcm;
use super::super::intmatrix::{IntMatrix, div_exact, divides};
use super::super::lattice::{column_hermite_normal_form, smith_normal_form_with_column_transform};
use super::super::poly_z::{invert_mod, reduce_mod};
use super::super::ratmatrix::{RatMatrix, rat_from_int};
use super::element::FieldElement;
use super::field::NumberField;

/// An order in a number field.
#[derive(Clone, Debug)]
pub(crate) struct Order {
    pub(super) field: NumberField,
    pub(super) basis: RatMatrix,
    pub(super) inverse_basis: RatMatrix,
    pub(super) multiplication: Vec<Vec<Vec<Int>>>,
    pub(super) index: Int,
    pub(super) discriminant: Int,
}

impl Order {
    /// The order generated by the power basis.
    pub(crate) fn power_basis(field: &NumberField) -> Option<Self> {
        let size = field.degree();
        Order::new(field.clone(), RatMatrix::identity(size))
    }

    /// Build an order from a rational basis whose columns are field elements.
    pub(crate) fn new(field: NumberField, basis: RatMatrix) -> Option<Self> {
        let size = field.degree();
        if basis.row_count() != size || basis.column_count() != size {
            return None;
        }
        let inverse_basis = basis.inverse()?;
        let determinant = basis.determinant()?.abs();
        if determinant.is_zero() {
            return None;
        }
        let index_ratio = Rat::one().div(&determinant).ok()?;
        if !index_ratio.den().is_one() {
            return None;
        }
        let index = index_ratio.num();
        let elements: Vec<FieldElement> = (0..size)
            .map(|column| field.element(basis.column(column)))
            .collect();
        let mut multiplication = vec![vec![vec![Int::zero(); size]; size]; size];
        for left in 0..size {
            for right in 0..size {
                let product = field.multiply(&elements[left], &elements[right]);
                let coordinates = inverse_basis.multiply(&RatMatrix::from_columns(vec![
                    product.coefficients().to_vec(),
                ])?)?;
                for (row, value) in coordinates.column(0).into_iter().enumerate() {
                    if !value.den().is_one() {
                        return None;
                    }
                    multiplication[left][right][row] = value.num();
                }
            }
        }
        let mut trace_rows = vec![vec![Rat::zero(); size]; size];
        for left in 0..size {
            for right in 0..size {
                let product = field.multiply(&elements[left], &elements[right]);
                trace_rows[left][right] = field.trace(&product)?;
            }
        }
        let trace_matrix = RatMatrix::from_rows(trace_rows)?;
        let discriminant = trace_matrix.determinant()?;
        if !discriminant.den().is_one() {
            return None;
        }
        let discriminant = discriminant.num();
        let squared_index = index.mul(&index);
        let expected = div_exact(field.power_discriminant(), &squared_index);
        if discriminant != expected {
            return None;
        }
        Some(Order {
            field,
            basis,
            inverse_basis,
            multiplication,
            index,
            discriminant,
        })
    }

    /// The field.
    pub(crate) fn field(&self) -> &NumberField {
        &self.field
    }

    /// The rational basis in the power basis.
    pub(crate) fn basis(&self) -> &RatMatrix {
        &self.basis
    }

    /// The multiplication table.
    pub(crate) fn multiplication_table(&self) -> &[Vec<Vec<Int>>] {
        &self.multiplication
    }

    /// The index `[Order : Z[alpha]]`.
    pub(crate) fn index(&self) -> &Int {
        &self.index
    }

    /// The order discriminant.
    pub(crate) fn discriminant(&self) -> &Int {
        &self.discriminant
    }

    /// True when `other` is contained in this order.
    pub(crate) fn contains(&self, other: &Order) -> Option<bool> {
        let coordinates = self.inverse_basis.multiply(&other.basis)?;
        Some(
            coordinates
                .to_rows()
                .iter()
                .flatten()
                .all(|value| value.den().is_one()),
        )
    }

    /// True when the multiplication table is associative.
    pub(crate) fn associativity_holds(&self) -> bool {
        let size = self.field.degree();
        for left in 0..size {
            for right in 0..size {
                for third in 0..size {
                    for output in 0..size {
                        let mut first = Int::zero();
                        let mut second = Int::zero();
                        for middle in 0..size {
                            first = first.add(
                                &self.multiplication[left][right][middle]
                                    .mul(&self.multiplication[middle][third][output]),
                            );
                            second = second.add(
                                &self.multiplication[right][third][middle]
                                    .mul(&self.multiplication[left][middle][output]),
                            );
                        }
                        if first != second {
                            return false;
                        }
                    }
                }
            }
        }
        true
    }

    /// True when every basis element is an algebraic integer.
    pub(crate) fn basis_is_integral(&self) -> bool {
        (0..self.field.degree()).all(|column| {
            let element = self.field.element(self.basis.column(column));
            self.field.is_integral(&element)
        })
    }

    /// The p-maximal overorder, or the same order when it is already
    /// p-maximal.
    pub(crate) fn p_maximal_overorder(&self, prime: &Int) -> Option<Order> {
        if prime.sign() <= 0 {
            return None;
        }
        let square = prime.mul(prime);
        if !divides(&square, &self.discriminant.abs()) {
            return Some(self.clone());
        }
        let size = self.field.degree();
        let images = self.frobenius_images(prime)?;
        let kernel = kernel_mod_prime(&images, prime)?;
        let mut generators = Vec::with_capacity(size + kernel.len());
        for index in 0..size {
            let mut column = vec![Int::zero(); size];
            column[index] = prime.clone();
            generators.push(column);
        }
        generators.extend(kernel);
        let ideal_basis = lattice_basis_columns(&generators, size)?;
        let ideal_matrix = RatMatrix::from_columns(
            ideal_basis
                .iter()
                .map(|column| column.iter().map(rat_from_int).collect())
                .collect(),
        )?;
        let ideal_inverse = ideal_matrix.inverse()?;
        let mut stacked_rows = Vec::with_capacity(size * size);
        for generator in &ideal_basis {
            let action = self.multiplication_by_coordinates(generator)?;
            let action = RatMatrix::from_rows(
                action
                    .to_rows()
                    .iter()
                    .map(|row| row.iter().map(rat_from_int).collect())
                    .collect(),
            )?;
            let quotient = ideal_inverse.multiply(&action)?;
            stacked_rows.extend(quotient.to_rows());
        }
        let stacked = RatMatrix::from_rows(stacked_rows)?;
        let mut denominator = Int::one();
        for row in stacked.to_rows().iter() {
            for value in row {
                denominator = lcm(&denominator, &value.den());
            }
        }
        let mut integer_rows = Vec::with_capacity(stacked.row_count());
        for row in stacked.to_rows() {
            let mut coefficients = Vec::with_capacity(row.len());
            for value in row {
                let scale = div_exact(&denominator, &value.den());
                coefficients.push(value.num().mul(&scale));
            }
            integer_rows.push(coefficients);
        }
        let matrix = IntMatrix::from_rows(integer_rows)?;
        let (diagonal, transform) = smith_normal_form_with_column_transform(&matrix)?;
        let modulus = prime.mul(&denominator);
        let mut coordinates = Vec::with_capacity(size);
        for index in 0..size {
            let diagonal_value = diagonal.get(index, index);
            let column_modulus = if diagonal_value.is_zero() {
                Int::one()
            } else {
                div_exact(&modulus, &modulus.gcd(&diagonal_value))
            };
            let column = transform.column(index);
            let mut rational_column = Vec::with_capacity(size);
            for value in column {
                rational_column
                    .push(Rat::from_ints(value.mul(&column_modulus), prime.clone()).ok()?);
            }
            coordinates.push(rational_column);
        }
        let coordinates = RatMatrix::from_columns(coordinates)?;
        let new_basis = self.basis.multiply(&coordinates)?;
        let next = Order::new(self.field.clone(), new_basis)?;
        if next.index().cmp(&self.index) == Ordering::Less {
            return None;
        }
        if !divides(&self.index, &next.index) {
            return None;
        }
        if next.contains(self) != Some(true) || !next.basis_is_integral() {
            return None;
        }
        Some(next)
    }

    /// The images of the basis elements under the p-power map on `O / pO`.
    fn frobenius_images(&self, prime: &Int) -> Option<Vec<Vec<Int>>> {
        let size = self.field.degree();
        let mut images = Vec::with_capacity(size);
        for index in 0..size {
            let mut basis = vec![Int::zero(); size];
            basis[index] = Int::one();
            images.push(power_mod_element(
                &basis,
                prime,
                &self.multiplication,
                prime,
            )?);
        }
        Some(images)
    }

    /// The matrix of multiplication by an element given in order coordinates.
    #[allow(clippy::needless_range_loop)]
    fn multiplication_by_coordinates(&self, coordinates: &[Int]) -> Option<IntMatrix> {
        let size = self.field.degree();
        let mut rows = vec![vec![Int::zero(); size]; size];
        for output in 0..size {
            for input in 0..size {
                let mut total = Int::zero();
                for index in 0..size {
                    total = total
                        .add(&coordinates[index].mul(&self.multiplication[input][index][output]));
                }
                rows[output][input] = total;
            }
        }
        IntMatrix::from_rows(rows)
    }
}

fn lattice_basis_columns(generators: &[Vec<Int>], size: usize) -> Option<Vec<Vec<Int>>> {
    let matrix = IntMatrix::from_columns(generators.to_vec())?;
    if matrix.row_count() != size {
        return None;
    }
    let form = column_hermite_normal_form(&matrix);
    if form.column_count() != size {
        return None;
    }
    Some((0..size).map(|column| form.column(column)).collect())
}

fn power_mod_element(
    base: &[Int],
    exponent: &Int,
    table: &[Vec<Vec<Int>>],
    prime: &Int,
) -> Option<Vec<Int>> {
    let size = base.len();
    let mut result = vec![Int::zero(); size];
    result[0] = Int::one();
    let mut factor = base
        .iter()
        .map(|value| reduce_mod(value, prime))
        .collect::<Vec<_>>();
    let mut exponent = exponent.clone();
    let two = Int::from_i64(2);
    while exponent.sign() > 0 {
        let (quotient, remainder) = exponent.divrem(&two).ok()?;
        if !remainder.is_zero() {
            result = multiply_mod(&result, &factor, table, prime)?;
        }
        exponent = quotient;
        if exponent.is_zero() {
            break;
        }
        factor = multiply_mod(&factor, &factor, table, prime)?;
    }
    Some(result)
}

fn multiply_mod(
    left: &[Int],
    right: &[Int],
    table: &[Vec<Vec<Int>>],
    prime: &Int,
) -> Option<Vec<Int>> {
    let size = left.len();
    let mut result = vec![Int::zero(); size];
    for left_index in 0..size {
        if left[left_index].is_zero() {
            continue;
        }
        for right_index in 0..size {
            if right[right_index].is_zero() {
                continue;
            }
            let coefficient = left[left_index].mul(&right[right_index]);
            for output in 0..size {
                result[output] =
                    result[output].add(&coefficient.mul(&table[left_index][right_index][output]));
            }
        }
    }
    for value in &mut result {
        *value = reduce_mod(value, prime);
    }
    Some(result)
}

#[allow(clippy::needless_range_loop)]
fn kernel_mod_prime(images: &[Vec<Int>], prime: &Int) -> Option<Vec<Vec<Int>>> {
    let size = images.len();
    if size == 0 {
        return Some(Vec::new());
    }
    let mut matrix = vec![vec![Int::zero(); size]; size];
    for column in 0..size {
        for row in 0..size {
            matrix[row][column] = reduce_mod(&images[column][row], prime);
        }
    }
    let mut pivots = Vec::new();
    let mut pivot_row = 0usize;
    for column in 0..size {
        if pivot_row >= size {
            break;
        }
        let Some(found) = (pivot_row..size).find(|row| !matrix[*row][column].is_zero()) else {
            continue;
        };
        matrix.swap(pivot_row, found);
        let inverse = invert_mod(&matrix[pivot_row][column], prime)?;
        for entry in 0..size {
            matrix[pivot_row][entry] = reduce_mod(&matrix[pivot_row][entry].mul(&inverse), prime);
        }
        for row in 0..size {
            if row == pivot_row {
                continue;
            }
            let factor = matrix[row][column].clone();
            if factor.is_zero() {
                continue;
            }
            for entry in 0..size {
                matrix[row][entry] = reduce_mod(
                    &matrix[row][entry].sub(&factor.mul(&matrix[pivot_row][entry])),
                    prime,
                );
            }
        }
        pivots.push(column);
        pivot_row += 1;
    }
    let mut free = Vec::new();
    for column in 0..size {
        if !pivots.contains(&column) {
            free.push(column);
        }
    }
    let mut basis = Vec::with_capacity(free.len());
    for free_column in free {
        let mut vector = vec![Int::zero(); size];
        vector[free_column] = Int::one();
        for (row, pivot_column) in pivots.iter().enumerate() {
            vector[*pivot_column] = reduce_mod(&matrix[row][free_column].neg(), prime);
        }
        basis.push(vector);
    }
    Some(basis)
}
